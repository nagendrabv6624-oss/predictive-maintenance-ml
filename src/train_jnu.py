"""Train/evaluate on measured JNU CSV files. Downloads official public recordings."""
from pathlib import Path
import urllib.request, csv, json
import numpy as np
from sklearn.ensemble import RandomForestClassifier, ExtraTreesClassifier
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline
from sklearn.svm import SVC

BASE=Path("data/JNU"); OUT=Path("outputs/jnu")
FILES={
 "normal":{600:"n600_3_2.csv",800:"n800_3_2.csv",1000:"n1000_3_2.csv"},
 "inner_race":{600:"ib600_2.csv",800:"ib800_2.csv",1000:"ib1000_2.csv"},
 "outer_race":{600:"ob600_2.csv",800:"ob800_2.csv",1000:"ob1000_2.csv"},
 "rolling_element":{600:"tb600_2.csv",800:"tb800_2.csv",1000:"tb1000_2.csv"}}
RAW="https://raw.githubusercontent.com/ClarkGableWang/JNU-Bearing-Dataset/master/{}"
def fetch():
 BASE.mkdir(parents=True,exist_ok=True)
 for label, speeds in FILES.items():
  for rpm,name in speeds.items():
   dest=BASE/name
   if not dest.exists() or dest.stat().st_size<10000:
    req=urllib.request.Request(RAW.format(name),headers={"User-Agent":"bearing-fault-project/1.0"})
    with urllib.request.urlopen(req,timeout=180) as r: dest.write_bytes(r.read())
   # Verify numeric content; HTML error pages must never be accepted as CSV.
   with dest.open(errors="replace") as f:
    vals=[]
    for line in f:
     try: vals.append(float(line.strip().split(",")[0]))
     except ValueError: continue
     if len(vals)>=100: break
   if len(vals)<100: raise RuntimeError(f"Recording failed numeric validation: {name}")
   print(f"Verified {name}: {dest.stat().st_size/1e6:.2f} MB")
def features(x,fs=50000):
 x=np.asarray(x,dtype=np.float32); x=x-np.mean(x)
 rms=np.sqrt(np.mean(x*x)); absx=np.abs(x)
 spec=np.abs(np.fft.rfft(x)); power=spec**2
 bands=np.array_split(power,12)
 return np.array([np.std(x),rms,np.max(absx),np.mean(absx),np.percentile(absx,95),
  np.mean(x**4)/(rms**4+1e-9),np.max(absx)/(rms+1e-9),
  *[np.sum(b)/(np.sum(power)+1e-9) for b in bands]],dtype=np.float32)
def load_windows():
 X=[];y=[];groups=[];speeds=[]
 for label,speeds_map in FILES.items():
  for rpm,name in speeds_map.items():
   data=np.loadtxt(BASE/name,dtype=np.float32,delimiter=",",ndmin=1)
   data=data.reshape(-1); length=2048; step=1024
   count=0
   for start in range(0,len(data)-length+1,step):
    w=data[start:start+length]
    X.append(features(w));y.append(label);groups.append(name);speeds.append(rpm);count+=1
   print(f"{name}: {len(data)} samples -> {count} windows")
 return np.asarray(X),np.asarray(y),np.asarray(groups),np.asarray(speeds)
def main():
 fetch();X,y,g,rpm=load_windows()
 # Leave one entire rotational speed out; no windows from a held-out recording leak into training.
 OUT.mkdir(parents=True,exist_ok=True); all_results={}
 for held in (600,800,1000):
  tr=rpm!=held;te=rpm==held
  models={"Random Forest":RandomForestClassifier(n_estimators=300,min_samples_leaf=2,class_weight="balanced",random_state=42,n_jobs=-1),
          "RBF SVM":make_pipeline(StandardScaler(),SVC(C=4,gamma="scale",class_weight="balanced"))}
  all_results[str(held)]={}
  for name,model in models.items():
   model.fit(X[tr],y[tr]);pred=model.predict(X[te])
   result={"accuracy":float(accuracy_score(y[te],pred)),"macro_f1":float(f1_score(y[te],pred,average="macro")),"classification_report":classification_report(y[te],pred,output_dict=True),"confusion_matrix":confusion_matrix(y[te],pred,labels=list(FILES)).tolist(),"test_windows":int(te.sum()),"held_out_speed_rpm":held,"held_out_files":sorted(set(g[te]))}
   all_results[str(held)][name]=result
   print(f"Hold out {held} rpm | {name}: accuracy={result['accuracy']:.4f}, macro-F1={result['macro_f1']:.4f}")
   if name=="Random Forest": 
    import joblib;joblib.dump(model,OUT/f"random_forest_holdout_{held}rpm.joblib")
 metrics={"dataset":"JNU Bearing Dataset (measured vibration recordings)","source":"https://github.com/ClarkGableWang/JNU-Bearing-Dataset","sampling_rate_hz":50000,"window_length_samples":2048,"hop_length_samples":1024,"split_policy":"Leave-one-rotational-speed-out; entire recordings held out by speed","classes":list(FILES),"recordings":{k:{str(r):v for r,v in d.items()} for k,d in FILES.items()},"results_by_held_out_speed":all_results,"note":"These are measured-data results generated by running this script. Do not quote results until the script has completed successfully and outputs have been inspected."}
 (OUT/"metrics.json").write_text(json.dumps(metrics,indent=2))
 print("Saved measured-data evaluation:",OUT/"metrics.json")
if __name__=="__main__":main()
